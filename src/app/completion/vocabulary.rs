pub(super) fn keywords() -> impl Iterator<Item = &'static str> {
    style::KEYWORDS
        .iter()
        .copied()
        .chain(EXTRA_KEYWORDS.split_ascii_whitespace())
}

pub(in crate::app) fn is_keyword(name: &str) -> bool {
    keywords().any(|keyword| keyword.eq_ignore_ascii_case(name))
}

pub(super) fn functions() -> impl Iterator<Item = &'static str> {
    FUNCTIONS.iter().map(|&(name, _)| name)
}

pub(in crate::app) fn parameters(name: &str) -> Option<&'static [&'static str]> {
    FUNCTIONS
        .iter()
        .find(|&&(function, _)| name.eq_ignore_ascii_case(function))
        .map(|&(_, parameters)| parameters)
}

